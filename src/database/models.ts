/* ------------------------------ RecurringTransaction -------------------------- */

/** Supported recurrence frequencies. Simple and mobile-friendly by design. */
export const RECURRING_FREQUENCIES = ['daily', 'weekly', 'monthly'] as const;
export type RecurringFrequency = (typeof RECURRING_FREQUENCIES)[number];

/**
 * A reusable rule that generates NORMAL expense/income rows on schedule
 * (table `recurring_transactions`, migration 004).
 *
 * A recurring rule is NOT a transaction: generated rows land in the regular
 * `expenses` / `income` tables and appear everywhere ordinary transactions
 * appear. Occurrence timestamps are local NOON epoch millis (same DST-safe
 * convention as record dates).
 */
export interface RecurringTransaction {
  id: number;
  /** Which side of the ledger the generated rows belong to. */
  type: CategoryType;
  /** Amount in minor units (paisa), always > 0. Never currency-converted. */
  amount: number;
  /** Expense title, or the income `source` of generated rows. */
  title: string;
  /** Expense rules only — income has no category FK (see migration 001). */
  categoryId: number | null;
  frequency: RecurringFrequency;
  /** First occurrence (local noon). Informational anchor after creation. */
  startDate: number;
  /** Next due occurrence (local noon). Advanced by the generation engine. */
  nextOccurrenceAt: number;
  /** Inclusive last occurrence (local noon); null = runs indefinitely. */
  endDate: number | null;
  /** Expense rules only — generated expenses reuse it for `payment_method`. */
  paymentMethod: PaymentMethod | null;
  note: string | null;
  /** false = paused: stored but never generates. */
  isActive: boolean;
  createdAt: number;
  updatedAt: number;
}

export interface RecurringTransactionDraft {
  type: CategoryType;
  amount: number;
  title: string;
  /** Required for expense rules; must stay null for income rules. */
  categoryId?: number | null;
  frequency: RecurringFrequency;
  /** First occurrence (local noon). */
  startDate: number;
  /** Defaults to `startDate` — the rule becomes due on its first occurrence. */
  nextOccurrenceAt?: number;
  endDate?: number | null;
  /** Required for expense rules; must stay null for income rules. */
  paymentMethod?: PaymentMethod | null;
  note?: string | null;
  isActive?: boolean;
}

/**
 * Fields allowed on update. `type` and `startDate` are intentionally NOT
 * patchable — moving a rule between expense/income (or re-anchoring its
 * history) would corrupt the generation semantics; delete and recreate
 * instead. `endDate: null` clears the end date.
 */
export interface RecurringTransactionPatch {
  amount?: number;
  title?: string;
  categoryId?: number;
  frequency?: RecurringFrequency;
  nextOccurrenceAt?: number;
  endDate?: number | null;
  paymentMethod?: PaymentMethod | null;
  note?: string | null;
}

export interface RecurringFilter {
  type?: CategoryType;
  isActive?: boolean;
}

/** Rule joined with its category — what the list screens display. */
export interface RecurringWithCategory extends RecurringTransaction {
  /** Null for income rules (which have no category). */
  categoryName: string | null;
  categoryIcon: string | null;
}

