/**
 * Type-safe models for the local database.
 *
 * Conventions (must stay in sync with `migrations.ts`):
 * - Money is ALWAYS stored as an integer in the smallest currency unit
 *   (e.g. paisa for PKR). Conversion to a display string happens only in the
 *   UI layer via `formatCurrency`.
 * - Timestamps (`createdAt`, `updatedAt`) and record dates (`date`) are
 *   epoch MILLISECONDS as integers.
 * - SQLite has no booleans: `isDefault` maps to an INTEGER 0/1 column and is
 *   converted in the category repository.
 */

export const CATEGORY_TYPES = ['expense', 'income'] as const;
export type CategoryType = (typeof CATEGORY_TYPES)[number];

export const PAYMENT_METHODS = [
  'cash',
  'card',
  'bank_transfer',
  'mobile_wallet',
  'other',
] as const;
export type PaymentMethod = (typeof PAYMENT_METHODS)[number];

/* ---------------------------------- Category --------------------------------- */

export interface Category {
  id: number;
  name: string;
  /**
   * Stable icon key (e.g. 'cart', 'bus'). The UI layer maps keys to actual
   * glyphs; the database never stores UI-specific values.
   */
  icon: string;
  type: CategoryType;
  isDefault: boolean;
  /**
   * false = archived/disabled. Disabled categories stay resolvable for
   * historical records and remain visible in management, but are excluded
   * from new-transaction pickers. Added by migration 003 (defaults true).
   */
  isActive: boolean;
  createdAt: number;
}

export interface CategoryDraft {
  name: string;
  icon: string;
  type: CategoryType;
  isDefault?: boolean;
}

/**
 * Fields allowed on update. `type` is intentionally NOT patchable — moving a
 * category between expense/income would silently corrupt existing records.
 */
export interface CategoryPatch {
  name?: string;
  icon?: string;
  isDefault?: boolean;
  /** Archive/restore a category without touching its historical records. */
  isActive?: boolean;
}

/* ---------------------------------- Expense ---------------------------------- */

export interface Expense {
  id: number;
  /** Amount in minor units (paisa), always > 0. */
  amount: number;
  title: string;
  categoryId: number;
  /** When the expense happened (epoch millis). */
  date: number;
  paymentMethod: PaymentMethod;
  note: string | null;
  createdAt: number;
  updatedAt: number;
  /**
   * Set on transactions GENERATED by a recurring rule (migration 004);
   * null/absent for manual records. Edits never change it — historical
   * generated rows stay normal, immutable transaction history.
   */
  recurringRuleId?: number | null;
}

export interface ExpenseDraft {
  amount: number;
  title: string;
  categoryId: number;
  date: number;
  paymentMethod: PaymentMethod;
  note?: string | null;
}

export interface ExpensePatch {
  amount?: number;
  title?: string;
  categoryId?: number;
  date?: number;
  paymentMethod?: PaymentMethod;
  note?: string | null;
}

export interface ExpenseFilter {
  categoryId?: number;
  paymentMethod?: PaymentMethod;
  /** Inclusive lower bound on `date` (epoch millis). */
  fromDate?: number;
  /** Inclusive upper bound on `date` (epoch millis). */
  toDate?: number;
  /** Inclusive lower bound on `amount` (minor units, > 0). Phase 11. */
  minAmount?: number;
  /** Inclusive upper bound on `amount` (minor units, > 0). Phase 11. */
  maxAmount?: number;
  /**
   * `true` → only rows GENERATED by a recurring rule
   * (`recurring_rule_id IS NOT NULL`); `false` → only manual rows
   * (`IS NULL`); `undefined` → both. Phase 11 — never inferred from
   * title/date; the column is the single source of truth.
   */
  recurring?: boolean;
  /**
   * Case-insensitive substring match against `title` OR `note` OR the
   * joined category `name` OR the `payment_method` value (Phase 11 —
   * whitespace-normalized; SQL LIKE wildcards in the term are matched
   * literally).
   */
  search?: string;
  limit?: number;
  offset?: number;
  /**
   * `amountDesc` (Phase 9) backs the "largest transaction" report insight;
   * ties resolve to the OLDEST row (id ASC) so results stay deterministic.
   * `amountAsc` (Phase 11) is the same contract in the other direction.
   */
  order?: 'dateDesc' | 'dateAsc' | 'amountDesc' | 'amountAsc';
}

/** Expense joined with its category — what list screens display. */
export interface ExpenseWithCategory extends Expense {
  categoryName: string;
  categoryIcon: string;
}

/** Aggregated spending per category, as returned by `sumByCategory`. */
export interface ExpenseCategoryTotal {
  categoryId: number;
  total: number;
}

/**
 * Spending AND frequency per category, as returned by `sumCountByCategory`
 * (Phase 9). One grouped query powers the category comparison list, the
 * "most frequent category" insight and per-category transaction counts —
 * callers must not loop per-category queries over this (no N+1).
 */
export interface ExpenseCategoryAggregate {
  categoryId: number;
  total: number;
  transactionCount: number;
}

/**
 * Aggregated spending for ONE calendar day, as returned by `sumByDay`.
 *
 * `dayIndex` is the 0-based offset from the `fromDate` anchor passed to
 * `sumByDay`, so it stays exact across DST transitions. Callers that need a
 * timestamp combine it with their own calendar-day list (see the reports
 * feature's `buildDailySeries`).
 */
export interface ExpenseDayTotal {
  dayIndex: number;
  total: number;
}

/* ----------------------------------- Income ---------------------------------- */

export interface Income {
  id: number;
  /** Amount in minor units (paisa), always > 0. */
  amount: number;
  /** Free-text source (e.g. 'Salary'). Kept as TEXT by design — see README. */
  source: string;
  /** When the income was received (epoch millis). */
  date: number;
  note: string | null;
  createdAt: number;
  updatedAt: number;
  /** Set on transactions GENERATED by a recurring rule (migration 004). */
  recurringRuleId?: number | null;
}

export interface IncomeDraft {
  amount: number;
  source: string;
  date: number;
  note?: string | null;
}

export interface IncomePatch {
  amount?: number;
  source?: string;
  date?: number;
  note?: string | null;
}

export interface IncomeFilter {
  fromDate?: number;
  toDate?: number;
  /** Inclusive lower bound on `amount` (minor units, > 0). Phase 11. */
  minAmount?: number;
  /** Inclusive upper bound on `amount` (minor units, > 0). Phase 11. */
  maxAmount?: number;
  /** Same contract as `ExpenseFilter.recurring` (Phase 11). */
  recurring?: boolean;
  /**
   * Exact source match (Phase 9) — income has no category FK, so the
   * category-detail screen filters rows by the exact stored `source` text
   * (the same string `sumBySource` groups by).
   */
  source?: string;
  /**
   * Case-insensitive substring match against `source` OR `note`
   * (whitespace-normalized since Phase 11; SQL LIKE wildcards in the term
   * are matched literally).
   */
  search?: string;
  limit?: number;
  offset?: number;
  /** `amountDesc` (Phase 9) backs the largest-transaction insight. */
  order?: 'dateDesc' | 'dateAsc' | 'amountDesc' | 'amountAsc';
}

/**
 * Aggregated income per source, as returned by `sumBySource` (Phase 9).
 * `source` is the exact free-text value stored on each income row.
 */
export interface IncomeSourceAggregate {
  source: string;
  total: number;
  transactionCount: number;
}

/**
 * Aggregated income for ONE calendar day, as returned by
 * `IncomeRepository.sumByDay`. Same `dayIndex` anchoring contract as
 * `ExpenseDayTotal` (0-based offset from the passed local-midnight
 * `fromDate`, exact across DST transitions).
 */
export interface IncomeDayTotal {
  dayIndex: number;
  total: number;
}

